export type IconName = keyof typeof ICONS;

export function icon(name: IconName, size = 22): SVGElement {
  const el = createElement(ICONS[name], { width: size, height: size, 'stroke-width': 1.9 });
  el.setAttribute('aria-hidden', 'true');
  return el;
}
